#include <unistd.h>

void	ft_putnbr(int nb)
{
	long	n;
	char	c;

	n = nb;
	if (n < 0)
	{
		write(1, "-", 1);
		n = -n;
	}
	if (n >= 10)
		ft_putnbr((int)(n / 10));
	c = (char)((n % 10) + '0');
	write(1, &c, 1);
}
