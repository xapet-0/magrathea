#include <unistd.h>

static int	in_str(char c, char *s, int limit)
{
	int	i;

	i = 0;
	while (s[i] && (limit < 0 || i < limit))
	{
		if (s[i] == c)
			return (1);
		i++;
	}
	return (0);
}

int	main(int argc, char **argv)
{
	int	i;

	if (argc == 3)
	{
		i = 0;
		while (argv[1][i])
		{
			if (!in_str(argv[1][i], argv[1], i) && in_str(argv[1][i], argv[2], -1))
				write(1, &argv[1][i], 1);
			i++;
		}
	}
	write(1, "\n", 1);
	return (0);
}
