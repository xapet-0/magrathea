#include <stdio.h>
#include <stdlib.h>

int	main(int argc, char **argv)
{
	int	a;
	int	b;
	int	t;

	if (argc == 3)
	{
		a = atoi(argv[1]);
		b = atoi(argv[2]);
		if (a > 0 && b > 0)
		{
			while (b != 0)
			{
				t = b;
				b = a % b;
				a = t;
			}
			printf("%d", a);
		}
	}
	printf("\n");
	return (0);
}
